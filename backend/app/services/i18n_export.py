def normalize_locale(value: str | None) -> Locale:
    if not value:
        return "de"
    v = value.strip().lower()
    if v.startswith("en"):
        return "en"
    return "de"


def t(locale: Locale, key: str, **params: object) -> str:
    catalog = _EXPORT_STRINGS.get(locale) or _EXPORT_STRINGS["de"]
    text = catalog.get(key) or _EXPORT_STRINGS["de"].get(key) or key
    if params:
        try:
            return text.format(**params)
        except (KeyError, ValueError):
            return text
    return text


def _copy_catalog(catalog: dict[str, str | list[str]]) -> dict[str, str | list[str]]:
    out: dict[str, str | list[str]] = {}
    for key, value in catalog.items():
        out[key] = list(value) if isinstance(value, list) else value
    return out


